class SystemDesignAlgorithm(QgsProcessingAlgorithm):

    # ---- Inputs -----------------------------------------------------------
    INPUT_LINES = 'VectorLineLayer'
    OUTLET = 'OUTLET'
    DEM = 'DEM'
    CRS = 'CRS'

    # e. Hydraulic Network Fixer
    START_EXT = 'StartPoints'
    END_EXT = 'EndPoints'

    # h. Network Elevation Exports
    SEGMENT_LENGTH = 'SegmentLength'

    # j. Tile Burying System
    UPPER = 'UPPER_DEPTH'
    LOWER = 'LOWER_DEPTH'
    ABS_UPPER = 'ABS_UPPER_DEPTH'
    ABS_LOWER = 'ABS_LOWER_DEPTH'
    MAX_SLOPE = 'MAX_SLOPE'
    MIN_SLOPE = 'MIN_SLOPE'
    OFFSET = 'OFFSET'
    CONST_SLOPE = 'CONST_SLOPE'
    USE_CONST = 'USE_CONST'

    # k. Network Pipe Sizing
    SIZING_SLOPE = 'SIZING_SLOPE'
    SPACING = 'SPACING'
    PIPE = 'PIPE'
    INTENSITY = 'INTENSITY'
    ASS_INTENSITY = 'ASS_INTENSITY'
    USE_ASS = 'USE_ASS'
    COEFF_METHOD = 'COEFF_METHOD'
    ORDER_COEFFS = 'ORDER_COEFFS'

    # ---- Outputs ----------------------------------------------------------
    OUT_PIPES = 'OUTPUT'
    OUT_FIXED = 'OUT_FIXED'
    OUT_NETWORK = 'OUT_NETWORK'
    OUT_ORDERING = 'OUT_ORDERING'
    OUT_ELEV_FIELDS = 'OUT_ELEV_FIELDS'
    OUT_ENDPOINTS = 'OUT_ENDPOINTS'
    OUT_PROFILES = 'OUT_PROFILES'
    OUT_FLOW_LENGTHS = 'OUT_FLOW_LENGTHS'
    OUT_BURIED = 'OUT_BURIED'

    def tr(self, string):
        return QCoreApplication.translate('Processing', string)

    def createInstance(self):
        return SystemDesignAlgorithm()

    def name(self):
        return 'Drainage System Design'

    def displayName(self):
        return self.tr(self.name())

    def group(self):
        return self.tr(self.groupId())

    def groupId(self):
        return ''

    def icon(self):
        cmd_folder = os.path.split(inspect.getfile(inspect.currentframe()))[0]
        return QIcon(os.path.join(cmd_folder, 'icon.svg'))

    def shortHelpString(self):
        return self.tr("""This tool designs a complete tile drainage system in one run. It performs, in order, the routines previously run separately as tools E through K:

        e. Hydraulic Network Fixer -- cleans the proposed lines into topologically-sound, exploded segments
        f. Network Flow-Path Generator -- connects the segments into a network flowing to the outlet
        g. Tile Network Ordering -- assigns flow, burying and Strahler orders
        h. Network Elevation Exports -- samples the DEM and calculates segment lengths and slopes
        i. Network Flow Lengths -- accumulates segment lengths downstream
        j. Tile Burying System -- calculates buried elevations, depths and slopes
        k. Network Pipe Sizing -- calculates drainage areas, flows and pipe sizes

        Workflow:
        1. Select the Vector Line layer of the proposed Mains and Submains
        2. Click on the map near the outlet end of the main to set the Outlet Location (the segment closest to this point becomes the outlet)
        3. Select the field DEM
        4. Set the burying and pipe sizing parameters (defaults are the same as the individual tools)
        5. Optionally, under Advanced Parameters, adjust line extension and segment length, and choose which intermediate layers (E to J) to save or load
        6. Click on \"Run\"

        The main output is \"Network Pipe Sizings\". Field names are passed between the steps automatically.

        The help link in the Graphical User Interface (GUI) provides more information about the plugin.
        """)

    def helpUrl(self):
        return "https://publish.illinois.edu/illinoisdrainageguide/files/2022/06/PublicAccess.pdf"

    # -----------------------------------------------------------------------
    def _advanced(self, parameter):
        parameter.setFlags(parameter.flags() | QgsProcessingParameterDefinition.FlagAdvanced)
        self.addParameter(parameter)

    def initAlgorithm(self, config=None):
        # --- Main inputs ---
        self.addParameter(QgsProcessingParameterVectorLayer(
            self.INPUT_LINES, self.tr('Proposed Tile Lines (Mains and Submains)'),
            types=[QgsProcessing.TypeVectorLine], defaultValue=None))
        self.addParameter(QgsProcessingParameterPoint(
            self.OUTLET, self.tr('Outlet Location (click near the outlet end of the main)')))
        self.addParameter(QgsProcessingParameterRasterLayer(
            self.DEM, self.tr('Original Field DEM'), defaultValue=None))
        self.addParameter(QgsProcessingParameterCrs(
            self.CRS, self.tr('Coordinate Reference System'), defaultValue='EPSG:3435'))

        # --- j. Burying parameters ---
        self.addParameter(QgsProcessingParameterNumber(self.UPPER, self.tr('Upper Tile Depth [ft]'), type=QgsProcessingParameterNumber.Double, maxValue=10.0, defaultValue=3.25))
        self.addParameter(QgsProcessingParameterNumber(self.LOWER, self.tr('Lower Tile Depth [ft]'), type=QgsProcessingParameterNumber.Double, maxValue=10.0, defaultValue=4.25))
        self.addParameter(QgsProcessingParameterNumber(self.ABS_UPPER, self.tr('Absolute Upper Tile Depth [ft]'), type=QgsProcessingParameterNumber.Double, maxValue=10.0, defaultValue=3.00))
        self.addParameter(QgsProcessingParameterNumber(self.ABS_LOWER, self.tr('Absolute Lower Tile Depth [ft]'), type=QgsProcessingParameterNumber.Double, maxValue=10.0, defaultValue=7.00))
        self.addParameter(QgsProcessingParameterNumber(self.MAX_SLOPE, self.tr('Maximum Slope Depth [percentage]'), type=QgsProcessingParameterNumber.Double, maxValue=100.0, defaultValue=5.00))
        self.addParameter(QgsProcessingParameterNumber(self.MIN_SLOPE, self.tr('Minimum Slope Depth [percentage]'), type=QgsProcessingParameterNumber.Double, maxValue=100.0, defaultValue=0.10))
        self.addParameter(QgsProcessingParameterNumber(self.OFFSET, self.tr('Offset Depth [ft]'), type=QgsProcessingParameterNumber.Double, maxValue=10.0, defaultValue=0.00))
        self.addParameter(QgsProcessingParameterNumber(self.CONST_SLOPE, self.tr('Constant Slope Depth [percentage]'), type=QgsProcessingParameterNumber.Double, maxValue=100.0, defaultValue=0.50, optional=True))
        self.addParameter(QgsProcessingParameterBoolean(self.USE_CONST, self.tr('Include Constant Slope [For Flat Terrain Only]'), defaultValue=False))

        # --- k. Pipe sizing parameters ---
        self.addParameter(QgsProcessingParameterEnum(self.SIZING_SLOPE, self.tr('Burying Slope used for Pipe Sizing'), options=[self.tr('InSlope'), self.tr('OutSlope')], defaultValue=0))
        self.addParameter(QgsProcessingParameterNumber(self.SPACING, self.tr('Drain Spacing [ft]'), type=QgsProcessingParameterNumber.Double, maxValue=200.0, defaultValue=80))
        self.addParameter(QgsProcessingParameterEnum(self.PIPE, self.tr('Select Pipe Material'), options=[self.tr("Single Wall"), self.tr("Smooth Wall"), self.tr("Clay or Concrete")], defaultValue=0))
        self.addParameter(QgsProcessingParameterEnum(self.INTENSITY, self.tr('Drainage Intensity [inch/day]'), options=[self.tr("A: 0.375"), self.tr("B: 0.500"), self.tr("C: 0.750"), self.tr("D: 1.000")], defaultValue=0))
        self.addParameter(QgsProcessingParameterNumber(self.ASS_INTENSITY, self.tr('E: others = Assign Intensity [inch/day]'), type=QgsProcessingParameterNumber.Double, maxValue=100.0, defaultValue=2.50, optional=True))
        self.addParameter(QgsProcessingParameterBoolean(self.USE_ASS, self.tr('Use Assigned Value'), defaultValue=False))

        # --- Advanced ---
        self._advanced(QgsProcessingParameterNumber(self.START_EXT, self.tr('E: Extend Starting Lines'), type=QgsProcessingParameterNumber.Double, maxValue=100.0, defaultValue=5.00))
        self._advanced(QgsProcessingParameterNumber(self.END_EXT, self.tr('E: Extend Ending Lines'), type=QgsProcessingParameterNumber.Double, maxValue=100.0, defaultValue=5.00))
        self._advanced(QgsProcessingParameterNumber(self.SEGMENT_LENGTH, self.tr('H: Line Segment (=> 5 times pixel size)'), type=QgsProcessingParameterNumber.Double, maxValue=1.79769e+308, defaultValue=5000))
        self._advanced(QgsProcessingParameterEnum(self.COEFF_METHOD, self.tr('K: Assign Drainage Coefficient [inch/day]'), options=[self.tr("By System [internal]"), self.tr("By Tile Orders [self]")], defaultValue=0))
        self._advanced(QgsProcessingParameterString(self.ORDER_COEFFS, self.tr("K: Order Coefficients separated by ',' (if \"By Tile Orders [self]\" selected)"), optional=True))

        # --- Outputs ---
        self.addParameter(QgsProcessingParameterFeatureSink(self.OUT_PIPES, self.tr('Network Pipe Sizings'), createByDefault=True, defaultValue=None))

        intermediates = [
            (self.OUT_FIXED, 'E: Topologically-Sound Network'),
            (self.OUT_NETWORK, 'F: Tile Network with Flow-Path'),
            (self.OUT_ORDERING, 'G: Tile Network Flow Ordering'),
            (self.OUT_ELEV_FIELDS, 'H: Reference Fields with Elevation Statistics'),
            (self.OUT_ENDPOINTS, 'H: End Point Elevations'),
            (self.OUT_PROFILES, 'H: Network Elevation Points'),
            (self.OUT_FLOW_LENGTHS, 'I: Cumulative Flow Lengths'),
            (self.OUT_BURIED, 'J: Buried Elevation Depths'),
        ]
        for key, label in intermediates:
            p = QgsProcessingParameterVectorDestination(key, self.tr(label), type=QgsProcessing.TypeVectorAnyGeometry, optional=True, createByDefault=False, defaultValue=None)
            p.setFlags(p.flags() | QgsProcessingParameterDefinition.FlagAdvanced)
            self.addParameter(p)

    # -----------------------------------------------------------------------
    @staticmethod
    def _dest(parameters, key):
        """Destination for a child step: the user's choice if set, otherwise a temporary layer."""
        value = parameters.get(key)
        if value is None or value == '':
            return QgsProcessing.TEMPORARY_OUTPUT
        return value

    @staticmethod
    def _wanted(parameters, key):
        value = parameters.get(key)
        return not (value is None or value == '')

    def _layer(self, layer_ref, context):
        layer = QgsProcessingUtils.mapLayerFromString(layer_ref, context)
        if layer is None:
            raise QgsProcessingException(self.tr('Could not load intermediate layer: {0}').format(layer_ref))
        return layer

    def _field(self, layer, name):
        """Return the exact (case-correct) field name in layer, or fail clearly."""
        idx = layer.fields().lookupField(name)
        if idx < 0:
            raise QgsProcessingException(self.tr('Field "{0}" not found in layer "{1}". Available fields: {2}').format(
                name, layer.name(), ', '.join(layer.fields().names())))
        return layer.fields().at(idx).name()

    @staticmethod
    def _child(cls):
        alg = cls()
        alg.initAlgorithm({})
        return alg

    def processAlgorithm(self, parameters, context, feedback):
        if (self.parameterAsEnum(parameters, self.COEFF_METHOD, context) == 1
                and not self.parameterAsString(parameters, self.ORDER_COEFFS, context).strip()):
            raise QgsProcessingException(self.tr('"By Tile Orders [self]" was selected, but no Order Coefficients were entered (e.g. 0.375, 0.47, 0.5).'))

        steps = QgsProcessingMultiStepFeedback(7, feedback)
        results = {}

        # ---------------- e. Hydraulic Network Fixer ----------------------
        steps.setCurrentStep(0)
        steps.pushInfo(self.tr('Step E: Hydraulic Network Fixer'))
        out_e = processing.run(self._child(GeometricallyFixedAlgorithm), {
            'VectorLineLayer': parameters[self.INPUT_LINES],
            'StartPoints': parameters[self.START_EXT],
            'EndPoints': parameters[self.END_EXT],
            'CRS': parameters[self.CRS],
            'LineFixes': self._dest(parameters, self.OUT_FIXED),
        }, context=context, feedback=steps, is_child_algorithm=True)['LineFixes']
        if steps.isCanceled():
            return {}
        if self._wanted(parameters, self.OUT_FIXED):
            results[self.OUT_FIXED] = out_e

        # ---------------- pick the outlet segment -------------------------
        fixed_layer = self._layer(out_e, context)
        outlet_pt = self.parameterAsPoint(parameters, self.OUTLET, context, fixed_layer.crs())
        outlet_geom = QgsGeometry.fromPointXY(outlet_pt)
        best_id, best_dist = None, None
        for f in fixed_layer.getFeatures():
            d = f.geometry().distance(outlet_geom)
            if best_dist is None or d < best_dist:
                best_id, best_dist = f.id(), d
        if best_id is None:
            raise QgsProcessingException(self.tr('Step E produced no line segments.'))
        fixed_layer.selectByIds([best_id])
        steps.pushInfo(self.tr('Outlet segment: feature {0} ({1:.2f} map units from the clicked point)').format(best_id, best_dist))

        # ---------------- f. Network Flow-Path Generator ------------------
        steps.setCurrentStep(1)
        steps.pushInfo(self.tr('Step F: Network Flow-Path Generator'))
        out_f = processing.run(self._child(NetworkGeneratorAlgorithm), {
            'INPUT_LINE': fixed_layer,
            'OUTPUT': self._dest(parameters, self.OUT_NETWORK),
        }, context=context, feedback=steps, is_child_algorithm=True)['OUTPUT']
        fixed_layer.removeSelection()
        if steps.isCanceled():
            return {}
        if self._wanted(parameters, self.OUT_NETWORK):
            results[self.OUT_NETWORK] = out_f

        # ---------------- g. Tile Network Ordering ------------------------
        steps.setCurrentStep(2)
        steps.pushInfo(self.tr('Step G: Tile Network Ordering'))
        layer_f = self._layer(out_f, context)
        out_g = processing.run(self._child(NetworkFlowOrderingAlgorithm), {
            'INPUT_LAYER': layer_f,
            'FROM_FIELD_KEY': self._field(layer_f, 'TILE_FROM'),
            'TO_FIELD_KEY': self._field(layer_f, 'TILE_TO'),
            'OUTPUT': self._dest(parameters, self.OUT_ORDERING),
        }, context=context, feedback=steps, is_child_algorithm=True)['OUTPUT']
        if steps.isCanceled():
            return {}
        if self._wanted(parameters, self.OUT_ORDERING):
            results[self.OUT_ORDERING] = out_g

        # ---------------- h. Network Elevation Exports --------------------
        steps.setCurrentStep(3)
        steps.pushInfo(self.tr('Step H: Network Elevation Exports'))
        layer_g = self._layer(out_g, context)
        res_h = processing.run(self._child(NetworkElevationAlgorithm), {
            'MDFT': parameters[self.DEM],
            'VERBOSE_LOG': True,
            'LineSegmentLayer': layer_g,
            'FGHTY': self._field(layer_g, 'TILE_ID'),
            'SegmentLength': parameters[self.SEGMENT_LENGTH],
            'CRS': parameters[self.CRS],
            'FinalFields': self._dest(parameters, self.OUT_ELEV_FIELDS),
            'EndpointElevations': self._dest(parameters, self.OUT_ENDPOINTS),
            'TerrainProfiles': self._dest(parameters, self.OUT_PROFILES),
        }, context=context, feedback=steps, is_child_algorithm=True)
        out_h = res_h['FinalFields']
        if steps.isCanceled():
            return {}
        if self._wanted(parameters, self.OUT_ELEV_FIELDS):
            results[self.OUT_ELEV_FIELDS] = out_h
        if self._wanted(parameters, self.OUT_ENDPOINTS):
            results[self.OUT_ENDPOINTS] = res_h['EndpointElevations']
        if self._wanted(parameters, self.OUT_PROFILES):
            results[self.OUT_PROFILES] = res_h['TerrainProfiles']

        # ---------------- i. Network Flow Lengths -------------------------
        steps.setCurrentStep(4)
        steps.pushInfo(self.tr('Step I: Network Flow Lengths'))
        layer_h = self._layer(out_h, context)
        length_field = self._field(layer_h, 'LENGTH')
        out_i = processing.run(self._child(FlowLengthsAlgorithm), {
            'INPUT_LAYER': layer_h,
            'INPUT_FIELD_CALC': length_field,
            'INPUT_FIELD_ID': self._field(layer_h, 'TILE_ID'),
            'INPUT_FIELD_NEXT': self._field(layer_h, 'TILE_TO'),
            'INPUT_FIELD_PREV': self._field(layer_h, 'TILE_FROM'),
            'OUTPUT': self._dest(parameters, self.OUT_FLOW_LENGTHS),
        }, context=context, feedback=steps, is_child_algorithm=True)['OUTPUT']
        if steps.isCanceled():
            return {}
        if self._wanted(parameters, self.OUT_FLOW_LENGTHS):
            results[self.OUT_FLOW_LENGTHS] = out_i

        # ---------------- j. Tile Burying System --------------------------
        steps.setCurrentStep(5)
        steps.pushInfo(self.tr('Step J: Tile Burying System'))
        layer_i = self._layer(out_i, context)
        out_j = processing.run(self._child(BuryAlgorithm), {
            BuryAlgorithm.INPUT_LAYER: layer_i,
            BuryAlgorithm.SEGMENT_KEY: self._field(layer_i, 'BURY_ORDER'),
            BuryAlgorithm.DIST_KEY: self._field(layer_i, 'LENGTH'),
            BuryAlgorithm.FIRST_KEY: self._field(layer_i, 'Elev_first'),
            BuryAlgorithm.LAST_KEY: self._field(layer_i, 'Elev_last'),
            BuryAlgorithm.UPPER_KEY: parameters[self.UPPER],
            BuryAlgorithm.LOWER_KEY: parameters[self.LOWER],
            BuryAlgorithm.ABS_UPPER_KEY: parameters[self.ABS_UPPER],
            BuryAlgorithm.ABS_LOWER_KEY: parameters[self.ABS_LOWER],
            BuryAlgorithm.MAXI_SLOPE_KEY: parameters[self.MAX_SLOPE],
            BuryAlgorithm.MINI_SLOPE_KEY: parameters[self.MIN_SLOPE],
            BuryAlgorithm.OFFSET_KEY: parameters[self.OFFSET],
            BuryAlgorithm.CONST_SLOPE_KEY: self.parameterAsDouble(parameters, self.CONST_SLOPE, context),
            BuryAlgorithm.USE_CONST_KEY: self.parameterAsBoolean(parameters, self.USE_CONST, context),
            BuryAlgorithm.OUTPUT: self._dest(parameters, self.OUT_BURIED),
        }, context=context, feedback=steps, is_child_algorithm=True)[BuryAlgorithm.OUTPUT]
        if steps.isCanceled():
            return {}
        if self._wanted(parameters, self.OUT_BURIED):
            results[self.OUT_BURIED] = out_j

        # ---------------- k. Network Pipe Sizing --------------------------
        steps.setCurrentStep(6)
        steps.pushInfo(self.tr('Step K: Network Pipe Sizing'))
        layer_j = self._layer(out_j, context)
        slope_name = ['InSlope', 'OutSlope'][self.parameterAsEnum(parameters, self.SIZING_SLOPE, context)]
        out_k = processing.run(self._child(BenefitsAlgorithm), {
            BenefitsAlgorithm.INPUT_LAYER: layer_j,
            BenefitsAlgorithm.SEGMENT_KEY: self._field(layer_j, 'TILE_ID'),
            BenefitsAlgorithm.TILE_TO_KEY: self._field(layer_j, 'TILE_TO'),
            BenefitsAlgorithm.ORDER_KEY: self._field(layer_j, 'TILE_ORDER'),
            BenefitsAlgorithm.LENGTH_KEY: self._field(layer_j, 'FLOW_' + length_field),
            BenefitsAlgorithm.SLOPE_KEY: self._field(layer_j, slope_name),
            BenefitsAlgorithm.SPACING_KEY: 0,  # single spacing value
            BenefitsAlgorithm.SINGLE_KEY: parameters[self.SPACING],
            BenefitsAlgorithm.PIPE_KEY: self.parameterAsEnum(parameters, self.PIPE, context),
            BenefitsAlgorithm.INTENS_KEY: self.parameterAsEnum(parameters, self.INTENSITY, context),
            BenefitsAlgorithm.ASS_INTENS_KEY: self.parameterAsDouble(parameters, self.ASS_INTENSITY, context),
            BenefitsAlgorithm.USE_ASS_KEY: self.parameterAsBoolean(parameters, self.USE_ASS, context),
            BenefitsAlgorithm.COFF_KEY: self.parameterAsEnum(parameters, self.COEFF_METHOD, context),
            BenefitsAlgorithm.ORDER_COFF_KEY: self.parameterAsString(parameters, self.ORDER_COEFFS, context),
            BenefitsAlgorithm.OUTPUT: parameters[self.OUT_PIPES],
        }, context=context, feedback=steps, is_child_algorithm=True)[BenefitsAlgorithm.OUTPUT]

        results[self.OUT_PIPES] = out_k
        return results
