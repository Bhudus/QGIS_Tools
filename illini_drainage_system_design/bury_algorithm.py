        self.addParameter(QgsProcessingParameterNumber(self.OFFSET_KEY, self.tr('Offset Depth [ft] (+ lowers the outlet)'), type=QgsProcessingParameterNumber.Double, maxValue=10.0, defaultValue=0.00))

